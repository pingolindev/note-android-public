package com.pingolin.note.ui.settings

import android.app.Application
import androidx.test.core.app.ApplicationProvider
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

/**
 * The third-party licence notices must actually ship.
 *
 * `assets/open_source_licenses.html` is generated by
 * `./gradlew :app:generateThirdPartyLicenses` and committed. Nothing in a
 * normal build regenerates it — that is deliberate, since regeneration needs a
 * `mobile-sdk` checkout for the native-crate half — but it also means a
 * dependency change can silently leave the notices stale, and a deleted asset
 * would surface only as a blank WebView on a screen nobody opens during
 * development. Attribution is a licence obligation, so it is checked here.
 *
 * This reads through the Android asset manager rather than off the filesystem,
 * so it proves the file is packaged for the variant rather than merely present
 * in the source tree.
 */
// A plain Application keeps NoteApplication's startup (Hilt, native library
// loading) out of a test that only needs the asset manager. Note the absence of
// manifest = Config.NONE: without the merged manifest there are no assets.
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [35], application = Application::class)
class OpenSourceLicensesAssetTest {

    private fun notices(): String =
        ApplicationProvider.getApplicationContext<Application>()
            .assets
            .open(LicensesFragment.ASSET_FILE)
            .bufferedReader()
            .use { it.readText() }

    @Test
    fun `notices asset is packaged and non-trivial`() {
        val html = notices()
        // The inventory runs to 166 JVM dependencies plus 284 Rust crates plus
        // the licence texts; anything near-empty means it was truncated or
        // replaced by a placeholder.
        assertTrue(
            "open_source_licenses.html is only ${html.length} chars",
            html.length > 50_000,
        )
        assertTrue(html.contains("<title>Open source licenses</title>"))
    }

    /**
     * JNA is dual-licensed LGPL-2.1-or-later / Apache-2.0. We ship under
     * Apache-2.0, and both halves of that have to be visible: naming only the
     * elected licence leaves a reader unable to tell an election from a plain
     * single-licence dependency.
     */
    @Test
    fun `JNA licence election is stated explicitly`() {
        val html = notices()
        assertTrue("JNA missing from notices", html.contains("net.java.dev.jna:jna"))
        // Pin the rendered forms, not the words. "elected" and "Apache-2.0"
        // asserted separately both pass on an asset where the election never
        // rendered at all: "Apache-2.0" alone appears in ~200 unrelated rows,
        // and a bare "elected" would be satisfied by any prose. These two
        // substrings only exist if the disclosure itself is intact.
        assertTrue(
            "the elected licence is not stated in the dependency row",
            html.contains("Apache-2.0 (elected)"),
        )
        assertTrue(
            "the offer being elected FROM is not stated",
            html.contains("offered under") && html.contains("LGPL-2.1-or-later"),
        )
    }

    /**
     * Components that are easy to lose in a regeneration. SQLCipher publishes a
     * `<license>` element with a URL and no name, so it is attributed only
     * because licenses/supplement.json fills it in; SQLite and OpenSSL are
     * inside SQLCipher's own libsqlcipher.so and appear on no classpath at all.
     */
    @Test
    fun `notable bundled components are attributed`() {
        val html = notices()
        listOf(
            "net.zetetic:sqlcipher-android",
            "org.mindrot:jbcrypt",
            "org.unifiedpush.android:connector",
            "com.google.firebase:firebase-messaging",
            "com.squareup.okhttp3:okhttp",
            "OpenSSL",
        ).forEach {
            assertTrue("$it missing from the licence notices", html.contains(it))
        }
        assertTrue("SQLCipher licence not resolved", html.contains("BSD-3-Clause"))
    }

    /**
     * The crates statically linked into the committed `.so` files are the half
     * of the inventory no classpath scan can see. If the native inventory ever
     * silently empties, the JVM half alone would still look plausible — so
     * assert on crates that only reach the APK through those binaries.
     */
    @Test
    fun `native Rust crates are attributed`() {
        val html = notices()
        listOf("libpingolin_mobile.so", "libnote_collab_sdk.so", "uniffi", "yrs")
            .forEach {
                assertTrue("$it missing from the licence notices", html.contains(it))
            }
    }

    /**
     * Apache-2.0 section 4(a) and MPL-2.0 section 3.2 both require a copy of
     * the licence to travel with the distribution, and SQLCipher's BSD terms
     * require its copyright line to be reproduced. Linking is not enough for
     * any of the three, so the texts themselves have to be in the asset.
     */
    @Test
    fun `licence texts are reproduced, not merely linked`() {
        val html = notices()
        assertTrue(
            "Apache-2.0 text missing",
            html.contains("TERMS AND CONDITIONS FOR USE, REPRODUCTION, AND DISTRIBUTION"),
        )
        assertTrue("MPL-2.0 text missing", html.contains("Mozilla Public License"))
        assertTrue(
            "SQLCipher copyright line missing",
            html.contains("ZETETIC, LLC"),
        )
    }
}
